"""Assemble references-updated.bib = KG_Bibliography (deduped) + WOS picks + corrections."""
import re
from pathlib import Path

ROOT = Path(r"D:/Research/Non-Stationarity-KG/03-writeup")

kg = (ROOT / "references" / "KG_Bibliography.bib").read_text(encoding="utf-8")
picks = (ROOT / "prior-art" / "WOS_key_picks.bib").read_text(encoding="utf-8")

# de-duplicate KG entries by key
kg_entries = re.split(r"(?m)^(?=@)", kg)
header = [e for e in kg_entries if e and not e.startswith("@")]
body = [e for e in kg_entries if e.startswith("@")]
seen, unique = set(), []
for e in body:
    m = re.match(r"@(\w+)\{([^,]+),", e)
    if not m:
        continue
    key = m.group(2).strip()
    if key in seen:
        continue
    seen.add(key)
    # Breiman CART book: cite the original 1984 edition (docx cites 1984)
    if key == "breiman2017classification":
        e = e.replace("year = {2017}", "year = {1984}")
    unique.append(e.rstrip() + "\n")

